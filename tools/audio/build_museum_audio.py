"""Prepare the generated museum music; synthesize an original ambient room.

Music source is preserved, never regenerated by this script. Python stdlib and
ffmpeg only. Audio processing is reproducible from the source + generation.json.
"""
from pathlib import Path
import array, hashlib, json, math, random, shutil, subprocess, wave

ROOT=Path(__file__).resolve().parents[2]
OUT=ROOT/"assets/audio/museum"
WORK=ROOT/"work/audio/museum"
RATE=44100
FFMPEG=shutil.which("ffmpeg")
if not FFMPEG:
    raise RuntimeError("ffmpeg is required")

def decode(path,channels):
    result=subprocess.check_output([FFMPEG,"-v","error","-i",str(path),"-ac",str(channels),
        "-ar",str(RATE),"-af","highpass=f=35,lowpass=f=14500","-f","f32le","-"])
    return array.array("f",result)

def wavefile(path,data,channels):
    pcm=array.array("h",(round(max(-.999,min(.999,v))*32767) for v in data))
    with wave.open(str(path),"wb") as w:
        w.setparams((channels,2,RATE,0,"NONE","not compressed"))
        w.writeframes(pcm.tobytes())

def periodic(data,channels,overlap):
    cross=round(overlap*RATE)
    frames=len(data)//channels
    result=data[cross*channels:]
    for i in range(cross):
        mix=.5-.5*math.cos(math.pi*i/(cross-1))
        for ch in range(channels):
            result[(frames-cross-cross+i)*channels+ch]=(
                data[(frames-cross+i)*channels+ch]*(1-mix)+data[i*channels+ch]*mix)
    return result

def normalize(data,channels,peak_db):
    means=[sum(data[c::channels])/(len(data)//channels) for c in range(channels)]
    for i in range(len(data)):
        data[i]-=means[i%channels]
    peak=max(map(abs,data))
    gain=10**(peak_db/20)/peak
    for i in range(len(data)):
        data[i]*=gain
    return data

def ambient():
    rng=random.Random(19061029)
    count=round(48.32*RATE)
    data=array.array("f")
    bass=body=dc=0.
    for i in range(count):
        t=i/RATE
        n=rng.uniform(-1,1)
        bass+=.006*(n-bass)
        body+=.039*(n-body)
        dc+=.0007*(n-dc)
        air=(bass-dc)*(.75+.12*math.sin(math.tau*.038*t))
        air+=(body-bass)*(.15+.035*math.sin(math.tau*.069*t+1.2))
        data.append(air)
    # Occasional tiny timber-settling transients, softened by sparse reflections.
    for at in [6.71,17.18,32.63,42.19]:
        for j in range(6):
            start=round((at+j*rng.uniform(.021,.053))*RATE)
            frequency=rng.uniform(120,340)
            amplitude=rng.uniform(.002,.0045)
            for i in range(round(.09*RATE)):
                t=i/RATE
                value=amplitude*min(1,t/.003)*math.exp(-t*59)*(
                    .65*math.sin(math.tau*frequency*t)+.35*rng.uniform(-1,1))
                for delay,gain in [(0,1),(.027,.23),(.059,.12)]:
                    ix=start+i+round(delay*RATE)
                    if ix<len(data):data[ix]+=value*gain
    return normalize(periodic(data,1,.32),1,-14.)

def encode(name,data,channels):
    temp=WORK/(name+".wav")
    wavefile(temp,data,channels)
    target=OUT/(name+".ogg")
    subprocess.run([FFMPEG,"-y","-v","error","-i",str(temp),"-c:a","libvorbis","-q:a","5",
                    "-fflags","+bitexact","-flags:a","+bitexact",str(target)],check=True)
    rms=math.sqrt(sum(v*v for v in data)/len(data))
    return {"seconds":len(data)/channels/RATE,"channels":channels,"sample_rate":RATE,
        "source_peak_dbfs":20*math.log10(max(map(abs,data))),
        "source_rms_dbfs":20*math.log10(rms),
        "source_seam_step":max(abs(data[ch]-data[-channels+ch]) for ch in range(channels)),
        "sha256":hashlib.sha256(target.read_bytes()).hexdigest(),
        "bytes":target.stat().st_size}

def main():
    WORK.mkdir(parents=True,exist_ok=True)
    (WORK/".gdignore").write_text("")
    source=OUT/"source/museum_original.mp3"
    music=decode(source,2)
    # A full 90-second miniature -> 84-second period, 6-second raised-cosine seam.
    music=normalize(periodic(music,2,6.),2,-5.)
    room=ambient()
    files={"museum_contemplation.ogg":encode("museum_contemplation",music,2),
           "museum_room.ogg":encode("museum_room",room,1)}
    # Audition uses the actual nominal in-game mix. It is not a game recording.
    preview=array.array("f")
    frames=len(music)//2
    for i in range(frames):
        fade=min(1.,i/(1.4*RATE),(frames-i-1)/(1.2*RATE))
        for ch in range(2):
            preview.append((music[i*2+ch]*10**(-11/20)+room[i%len(room)]*10**(-14/20))*fade)
    wavefile(WORK/"museum-audition.wav",preview,2)
    subprocess.run([FFMPEG,"-y","-v","error","-i",str(WORK/"museum-audition.wav"),
        "-c:a","libmp3lame","-b:a","192k",str(WORK/"museum-audition.mp3")],check=True)
    seam=music[-12*RATE*2:]+music[:12*RATE*2]
    wavefile(WORK/"museum-loop-seam.wav",seam,2)
    manifest={"music_source":{"provider":"ElevenLabs","model":"eleven_music_v2",
        "generation_id":"H1SzIeW1xMyOEFs8GI10","sha256":hashlib.sha256(source.read_bytes()).hexdigest()},
        "ambience_source":"Original deterministic synthesis; no external recordings.",
        "processing":"35 Hz HP / 14.5 kHz LP music; 6 s raised-cosine overlap; DC removal; peak -5 dBFS; Vorbis q5. Room 320 ms overlap, peak -14 dBFS.",
        "files":files}
    (OUT/"manifest.json").write_text(json.dumps(manifest,indent=2)+"\n",encoding="utf-8")
    print("MUSEUM AUDIO:",json.dumps(files))
    print("Audition: work/audio/museum/museum-audition.mp3")

if __name__=="__main__":main()
